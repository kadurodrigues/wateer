-- Accounts and sync: each signed-in user's queue, bookmarks, tags, history and
-- settings. Row-level security limits every table to the signed-in user's rows,
-- so the browser can talk to the database directly with the publishable key.
-- See docs/adr/0002-accounts-and-sync.md.

-- updated_at is set by the database, never the client, so "latest write wins"
-- compares clocks from one source.
create function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- Videos -------------------------------------------------------------------------

create table public.videos (
  -- Generated by the client, so a video has the same id before and after it syncs.
  id uuid primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  video_id text not null check (video_id ~ '^[A-Za-z0-9_-]{11}$'),
  url text not null check (length(url) <= 2048),
  title text check (length(title) <= 500),
  channel_name text check (length(channel_name) <= 200),
  duration integer check (duration > 0),
  comment_count bigint check (comment_count >= 0),
  watched boolean not null default false,
  bookmarked boolean not null default false,
  in_queue boolean not null default true,
  -- Sort key. Moving a video gives it a value between its new neighbours,
  -- so a reorder touches one row.
  position double precision not null,
  playback_seconds integer not null default 0 check (playback_seconds >= 0),
  added_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, video_id)
);

create index videos_user_position_idx on public.videos (user_id, position);

create trigger videos_set_updated_at
before insert or update on public.videos
for each row execute function public.set_updated_at();

-- Tags ---------------------------------------------------------------------------

create table public.tags (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null check (length(btrim(name)) between 1 and 100),
  color text not null check (
    color in ('red', 'orange', 'amber', 'green', 'teal', 'blue', 'violet', 'pink', 'slate')
  ),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Tag names are unique per user regardless of case, as in the app.
create unique index tags_user_name_idx on public.tags (user_id, lower(name));

create trigger tags_set_updated_at
before insert or update on public.tags
for each row execute function public.set_updated_at();

-- Which tags are applied to which videos. user_id is denormalised so policies and
-- realtime filters don't need a join.
create table public.video_tags (
  video_id uuid not null references public.videos (id) on delete cascade,
  tag_id uuid not null references public.tags (id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (video_id, tag_id)
);

create index video_tags_tag_idx on public.video_tags (tag_id);
create index video_tags_user_idx on public.video_tags (user_id);

-- History ------------------------------------------------------------------------

create table public.history (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  video_id text not null check (video_id ~ '^[A-Za-z0-9_-]{11}$'),
  url text not null check (length(url) <= 2048),
  title text check (length(title) <= 500),
  added_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (user_id, video_id)
);

create trigger history_set_updated_at
before insert or update on public.history
for each row execute function public.set_updated_at();

-- Settings -----------------------------------------------------------------------

create table public.user_settings (
  user_id uuid primary key default auth.uid() references auth.users (id) on delete cascade,
  auto_play_next boolean not null default false,
  updated_at timestamptz not null default now()
);

create trigger user_settings_set_updated_at
before insert or update on public.user_settings
for each row execute function public.set_updated_at();

-- Row-level security -----------------------------------------------------------------
-- (select auth.uid()) is evaluated once per statement rather than once per row.

alter table public.videos enable row level security;
alter table public.tags enable row level security;
alter table public.video_tags enable row level security;
alter table public.history enable row level security;
alter table public.user_settings enable row level security;

create policy "Own videos" on public.videos
for all to authenticated
using (user_id = (select auth.uid()))
with check (user_id = (select auth.uid()));

create policy "Own tags" on public.tags
for all to authenticated
using (user_id = (select auth.uid()))
with check (user_id = (select auth.uid()));

-- Both ends of the link must belong to the same user as the row itself.
-- Columns are qualified: inside the subquery a bare video_id would mean v.video_id.
create policy "Own video tags" on public.video_tags
for all to authenticated
using (user_id = (select auth.uid()))
with check (
  user_id = (select auth.uid())
  and exists (
    select 1 from public.videos v
    where v.id = video_tags.video_id and v.user_id = (select auth.uid())
  )
  and exists (
    select 1 from public.tags t
    where t.id = video_tags.tag_id and t.user_id = (select auth.uid())
  )
);

create policy "Own history" on public.history
for all to authenticated
using (user_id = (select auth.uid()))
with check (user_id = (select auth.uid()));

create policy "Own settings" on public.user_settings
for all to authenticated
using (user_id = (select auth.uid()))
with check (user_id = (select auth.uid()));

-- Signed-out visitors get nothing; signed-in users get exactly what the policies allow.
revoke all on public.videos, public.tags, public.video_tags, public.history, public.user_settings
from anon;
grant select, insert, update, delete
on public.videos, public.tags, public.video_tags, public.history, public.user_settings
to authenticated;

-- Realtime -----------------------------------------------------------------------
-- Changes made on one device reach the others. Realtime applies the policies above
-- to inserts and updates; delete events carry only the primary key.

alter publication supabase_realtime
add table public.videos, public.tags, public.video_tags, public.history, public.user_settings;
